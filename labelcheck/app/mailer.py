"""Outgoing e-mail (password reset, invites, review notifications).

With LABELCHECK_SMTP_HOST set, mail goes through that SMTP server (Gmail, Amazon SES,
SendGrid, Office 365, Mailgun, Brevo, ...). Without it, mails are written to the log (development).
Sending happens on a background thread, so a slow mail server never slows down a request.
The last 50 mails are kept in memory (`OUTBOX`) for tests and debugging.
"""
import html as html_lib
import logging
import smtplib
import ssl
import threading
from collections import deque
from email.message import EmailMessage
from email.utils import make_msgid

from .config import settings

log = logging.getLogger("labelcheck.mail")
OUTBOX = deque(maxlen=50)


def _send_now(msg):
    host = settings.smtp_host
    if not host:
        raise RuntimeError("No SMTP server configured (LABELCHECK_SMTP_HOST is empty).")
    ctx = ssl.create_default_context()
    if settings.smtp_tls == "ssl":
        server = smtplib.SMTP_SSL(host, settings.smtp_port, context=ctx, timeout=20)
    else:
        server = smtplib.SMTP(host, settings.smtp_port, timeout=20)
        if settings.smtp_tls == "starttls":
            server.starttls(context=ctx)
    with server:
        if settings.smtp_user:
            server.login(settings.smtp_user, settings.smtp_password or "")
        server.send_message(msg)


def _worker(msg):
    try:
        _send_now(msg)
        log.info("mail sent to %s: %s", msg["To"], msg["Subject"])
    except Exception as e:  # never crash the caller because of background mail failure
        log.error("mail to %s failed: %s", msg["To"], e)


