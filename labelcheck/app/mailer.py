def send(to, subject, text, html=None, wait=False):
    msg = EmailMessage()
    msg["From"] = settings.mail_from
    msg["To"] = to
    msg["Subject"] = subject
    msg["Message-ID"] = make_msgid(domain="labelcheck")
    msg.set_content(text + "\n\n-- \nLabelCheck. This is an automatic message.\n")
    if html:
        msg.add_alternative(html, subtype="html")
    OUTBOX.append({"to": to, "subject": subject, "text": text, "html": html})
    if not settings.smtp_host:
        if settings.production:
            log.warning("no SMTP server: mail to %s not sent (%s)", to, subject)
        else:
            log.info("DEV MAIL to %s | %s\n%s", to, subject, text)
        return
    if wait:
        _send_now(msg)
    else:
        t = threading.Thread(target=_worker, args=(msg,), daemon=True)
        t.start()


